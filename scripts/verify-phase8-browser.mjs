// Isolated fixture API + deployed frontend. Playwright is a verification-only tool.
// PLAYWRIGHT_MODULE, PHASE8_FIXTURE, PHASE8_SCREENSHOTS must be set explicitly.
import { readFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
import assert from 'node:assert/strict'
import { error as reportError, info } from './lib/cli-report.mjs'
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href)
const fixture = JSON.parse(await readFile(process.env.PHASE8_FIXTURE, 'utf8'))
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.route('**/api/**', async route => {
  const source = new URL(route.request().url())
  const response = await route.fetch({ url: `http://127.0.0.1:5001${source.pathname}${source.search}` })
  await route.fulfill({ response })
})
await page.route('**/phase8-radar.svg', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="1000"><rect width="1000" height="1000" fill="#27384d"/><path d="M100 100H400V400H100ZM600 600H900V900H600Z" fill="#506884"/><text x="200" y="250" fill="white" font-size="40">A</text><text x="700" y="750" fill="white" font-size="40">B</text></svg>' }))
// Token key follows services/api.js.
await page.addInitScript(token => localStorage.setItem('cs2_auth_token', token), fixture.token)
try {
  await page.goto('http://localhost/maps')
  await page.getByLabel('Buscar mapa').waitFor()
  await page.goto(`http://localhost/maps/${fixture.map_id}`)
  await page.getByRole('button', { name: 'Estrategias', exact: true }).click()
  await page.getByRole('button', { name: 'Nueva estrategia', exact: true }).click()
  await page.getByLabel('Nombre de estrategia').fill('Browser execute')
  await page.getByLabel('Alineación').selectOption(String(fixture.lineup_id))
  await page.getByLabel('Herramienta').selectOption('marker')
  const board = page.getByLabel(/Plano táctico de/)
  const box = await board.boundingBox()
  await board.click({ position: { x: box.width * .35, y: box.height * .4 } })
  await page.getByLabel('Texto del elemento').fill('Entry position')
  await page.getByLabel('Jugador asignado').selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Guardar estrategia', exact: true }).click()
  await page.getByText('Guardada · versión 1', { exact: true }).waitFor()
  await page.screenshot({ path: `${process.env.PHASE8_SCREENSHOTS}/tactical-desktop.png`, fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: 'Estrategias', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir estrategia', exact: true }).first().click()
  await page.getByRole('button', { name: 'marker P1' }).waitFor()
  const response = await page.request.get(`http://127.0.0.1:5001/api/teams/${fixture.team_id}/strategies`, { headers: { Authorization: `Bearer ${fixture.token}` } })
  const data = await response.json()
  const point = data.strategies[0].document.elements[0].points[0]
  assert(point.every(n => n >= 0 && n <= 1), 'Coordinates must persist normalized')
  assert(data.strategies[0].lineup_id === fixture.lineup_id)
  for (const width of [768, 390]) {
    await page.setViewportSize({ width, height: 900 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Horizontal overflow at ${width}px`)
    await page.screenshot({ path: `${process.env.PHASE8_SCREENSHOTS}/tactical-${width}.png`, fullPage: true })
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Preparación', exact: true }).click()
  await page.getByLabel('Alineación seleccionada').selectOption(String(fixture.lineup_id))
  await page.locator('.preparation-form select').nth(1).selectOption('READY')
  await page.getByLabel('Notas de preparación').fill('Browser preparation persists')
  await page.getByRole('button', { name: 'Guardar preparación', exact: true }).click()
  await page.getByText('Cambios guardados.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Granadas', exact: true }).click()
  await page.getByRole('button', { name: 'Nueva granada', exact: true }).click()
  await page.getByLabel('Nombre', { exact: true }).fill('Browser smoke')
  await page.getByLabel('Video YouTube').fill('https://youtu.be/dQw4w9WgXcQ')
  await page.getByLabel('Instrucciones').fill('Stand still, aim at the corner, throw.')
  await page.getByRole('button', { name: 'Guardar granada', exact: true }).click()
  await page.getByRole('heading', { name: 'Browser smoke', exact: true }).last().waitFor()
  await page.getByRole('button', { name: 'Favorito', exact: true }).last().click()
  await page.getByRole('button', { name: 'Quitar favorito', exact: true }).last().waitFor()
  await page.goto(`http://localhost/teams/${fixture.team_id}/lineups`)
  await page.getByRole('button', { name: 'Nueva alineación', exact: true }).click()
  await page.getByLabel('Nombre', { exact: true }).fill('Browser Alternate')
  await page.getByLabel('Mapa asociado').selectOption(String(fixture.map_id))
  await page.getByRole('button', { name: 'Crear alineación', exact: true }).click()
  await page.getByRole('heading', { name: 'Browser Alternate', exact: true }).waitFor()
  await page.getByRole('heading', { name: 'Historial de alineaciones', exact: true }).waitFor()
  await page.goto(`http://localhost/teams/${fixture.team_id}/lineups`)
  await page.getByLabel('Primera alineación').selectOption({ label: 'Browser Main' })
  await page.getByLabel('Segunda alineación').selectOption({ label: 'Browser Alternate' })
  await page.getByRole('button', { name: 'Comparar', exact: true }).click()
  await page.getByText(/El ELO individual no representa/).waitFor()
  await page.screenshot({ path: `${process.env.PHASE8_SCREENSHOTS}/lineup-comparison.png`, fullPage: true })
  assert.deepEqual(errors, [])
  info('Browser OK: library, strategy creation, lineup selection, marker save/reload, normalized persistence, preparation, private grenade creation, favorites, map lineup creation, history, comparison, 1440/768/390px layouts; no JS errors.')
} catch (error) {
  reportError('Visible alerts:', await page.getByRole('alert').allTextContents())
  reportError('JS errors:', errors)
  await page.screenshot({ path: `${process.env.PHASE8_SCREENSHOTS}/tactical-failure.png`, fullPage: true })
  throw error
} finally {
  await browser.close()
}
